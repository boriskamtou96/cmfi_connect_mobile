// Writes lib/src/core/i18n/country_names.dart: the name of each country in
// the 7 languages of the app, and the countries sorted by name in each one.
// The names come from the Unicode CLDR data built into Node (Intl), the
// countries from phone_numbers_parser (every country that has phone numbers).
//
//   node tool/country_names.mjs
//
// Run it again after adding a language or upgrading phone_numbers_parser.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const languages = ['fr', 'en', 'de', 'es', 'ar', 'zh', 'hi'];

const packages = JSON.parse(
  readFileSync(join(root, '.dart_tool/package_config.json'), 'utf8'),
).packages;
const parser = packages.find((p) => p.name === 'phone_numbers_parser');
if (!parser) {
  throw new Error('phone_numbers_parser not found: run flutter pub get');
}
const parserRoot = parser.rootUri.startsWith('file:')
  ? fileURLToPath(parser.rootUri)
  : join(root, '.dart_tool', parser.rootUri);
const isoSource = readFileSync(
  join(parserRoot, 'lib/src/iso_codes/iso_code.dart'),
  'utf8',
);
const codes = [...isoSource.matchAll(/^ {2}([A-Z]{2}),$/gm)].map((m) => m[1]);

const quote = (s) => `'${s.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;

const names = {};
const sorted = {};
for (const language of languages) {
  const display = new Intl.DisplayNames([language], { type: 'region' });
  names[language] = Object.fromEntries(codes.map((c) => [c, display.of(c)]));
  const collator = new Intl.Collator(language);
  sorted[language] = [...codes].sort((a, b) =>
    collator.compare(names[language][a], names[language][b]),
  );
}

let out = `// Generated by \`node tool/country_names.mjs\` (Unicode CLDR names): do not edit.

/// Name of each country by ISO code ("CM"), in each language of the app.
const countryNames = <String, Map<String, String>>{
`;
for (const language of languages) {
  out += `  '${language}': {\n`;
  for (const code of codes) {
    out += `    '${code}': ${quote(names[language][code])},\n`;
  }
  out += '  },\n';
}
out += `};

/// The ISO codes in the alphabetical order of each language.
const countryCodesByName = <String, List<String>>{
`;
for (const language of languages) {
  out += `  '${language}': [\n`;
  for (let i = 0; i < codes.length; i += 12) {
    out += `    ${sorted[language].slice(i, i + 12).map(quote).join(', ')},\n`;
  }
  out += '  ],\n';
}
out += '};\n';

const target = join(root, 'lib/src/core/i18n/country_names.dart');
writeFileSync(target, out);
execFileSync('dart', ['format', target], { stdio: 'ignore' });
console.log(`${codes.length} countries in ${languages.length} languages`);
